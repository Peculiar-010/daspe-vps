const fs = require('fs').promises;
const path = require('path');
const { execFileSync } = require('child_process');

const BASE_DOMAIN = process.env.BASE_DOMAIN || 'daspe.name.ng';
const ROUTES_FILE = '/etc/caddy/daspe-deployments.caddy';
const MAIN_CONFIG = '/etc/caddy/Caddyfile';

const validateDomain = (domain) => {
  if (
    typeof domain !== 'string' ||
    domain.length > 253 ||
    !/^(?=.{1,253}$)(?:[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)(?:\.(?:[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?))*$/.test(domain)
  ) {
    throw new Error(`Invalid deployment domain: ${domain}`);
  }

  return domain.toLowerCase();
};

const validateTarget = (ip, port) => {
  if (
    typeof ip !== 'string' ||
    !/^[0-9a-fA-F:.]+$/.test(ip) ||
    !Number.isInteger(Number(port)) ||
    Number(port) < 1 ||
    Number(port) > 65535
  ) {
    throw new Error('Invalid container IP or target port');
  }
};

const generateCaddyConfig = async () => {
  const { query } = require('../config/database');

  const result = await query(`
    SELECT d.id, d.subdomain, d.custom_domain, d.status,
           dr.domain, dr.target_ip, dr.target_port, d.port
    FROM deployments d
    LEFT JOIN domain_routes dr ON dr.deployment_id = d.id
    WHERE d.status = 'running'
  `);

  const blocks = [];

  for (const dep of result.rows) {
    const domain = validateDomain(
      dep.domain || dep.custom_domain || `${dep.subdomain}.${BASE_DOMAIN}`
    );

    if (!dep.target_ip) {
      console.warn(`[Caddy] Skipping ${domain}: target_ip is missing`);
      continue;
    }

    const port = Number(dep.target_port || dep.port || 3000);
    validateTarget(dep.target_ip, port);

    // IPv6 addresses must be enclosed in brackets in an upstream address.
    const host = dep.target_ip.includes(':')
      ? `[${dep.target_ip}]`
      : dep.target_ip;

    blocks.push(`
http://${domain} {
    @blocked {
        path /.env /.env.* /.git/* /.htaccess /.DS_Store
        path_regexp sensitive \\.(env|git|htaccess|DS_Store|sql|log|bak|backup|conf|config|ini|key|pem|cert|crt)$
    }
    respond @blocked 403

    encode gzip
    header {
        X-Frame-Options DENY
        X-Content-Type-Options nosniff
        Referrer-Policy strict-origin-when-cross-origin
        -Server
    }

    reverse_proxy ${host}:${port}
}
`);
  }

  const content = `# Automatically generated by Daspe.
# Do not edit manually.
# Cloudflare terminates public HTTPS; this origin route uses HTTP.
${blocks.join('\n')}
`;

  const tempFile = `/tmp/daspe-deployments-${process.pid}.caddy`;

  await fs.writeFile(tempFile, content, { mode: 0o644 });

  try {
    execFileSync('/usr/bin/sudo', [
      '-n',
      '/usr/bin/install',
      '-o',
      'root',
      '-g',
      'caddy',
      '-m',
      '0640',
      tempFile,
      ROUTES_FILE
    ], { stdio: 'inherit', timeout: 10000 });
  } finally {
    await fs.unlink(tempFile).catch(() => {});
  }

  return { routes: blocks.length };
};

const regenerateCaddy = async () => {
  await generateCaddyConfig();

  // Validate the full active configuration before applying it.
  execFileSync('sudo', [
    '/usr/bin/caddy',
    'validate',
    '--config',
    MAIN_CONFIG,
    '--adapter',
    'caddyfile'
  ], { stdio: 'inherit', timeout: 15000 });

  // If reload fails, throw an error rather than reporting success.
  execFileSync('sudo', [
    '/usr/bin/systemctl',
    'reload',
    'caddy'
  ], { stdio: 'inherit', timeout: 15000 });
};

const updateCaddyRoute = async (domain, containerIp, port, deploymentId) => {
  const { query } = require('../config/database');

  const safeDomain = validateDomain(domain);
  validateTarget(containerIp, Number(port));

  await query(`
    INSERT INTO domain_routes
      (deployment_id, domain, target_ip, target_port)
    VALUES ($1, $2, $3, $4)
    ON CONFLICT (domain)
    DO UPDATE SET
      deployment_id = EXCLUDED.deployment_id,
      target_ip = EXCLUDED.target_ip,
      target_port = EXCLUDED.target_port
  `, [deploymentId, safeDomain, containerIp, Number(port)]);

  await regenerateCaddy();
};

const removeCaddyRoute = async (deploymentId) => {
  const { query } = require('../config/database');

  await query(
    'DELETE FROM domain_routes WHERE deployment_id = $1',
    [deploymentId]
  );

  await regenerateCaddy();
};

module.exports = {
  generateCaddyConfig,
  updateCaddyRoute,
  removeCaddyRoute,
  regenerateCaddy
};
